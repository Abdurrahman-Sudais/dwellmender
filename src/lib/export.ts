import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function toCSV(rows: Record<string, string | number>[]) {
  if (!rows.length) return "";
  const headers = Object.keys(rows[0]);
  const esc = (v: string | number) => {
    const s = String(v ?? "");
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return [headers.join(","), ...rows.map((r) => headers.map((h) => esc(r[h])).join(","))].join("\n");
}

export function downloadCSV(filename: string, rows: Record<string, string | number>[]) {
  triggerDownload(new Blob([toCSV(rows)], { type: "text/csv;charset=utf-8" }), filename);
}

export interface PdfSection {
  title: string;
  subtitle?: string;
  head: string[];
  body: (string | number)[][];
}

export function downloadPDF(filename: string, title: string, meta: string, sections: PdfSection[], summary?: [string, string][]) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const navy: [number, number, number] = [19, 35, 63];
  const pageW = doc.internal.pageSize.getWidth();

  doc.setFillColor(...navy);
  doc.rect(0, 0, pageW, 70, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("DwellMender", 40, 34);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Find recurring property problems sooner.", 40, 52);

  doc.setTextColor(...navy);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(title, 40, 104);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(meta, 40, 120);

  let y = 140;
  if (summary?.length) {
    const colW = (pageW - 80) / Math.min(summary.length, 4);
    summary.slice(0, 4).forEach(([label, value], i) => {
      const x = 40 + i * colW;
      doc.setFillColor(250, 247, 242);
      doc.roundedRect(x, y, colW - 8, 48, 4, 4, "F");
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(label, x + 10, y + 16);
      doc.setFontSize(14);
      doc.setTextColor(...navy);
      doc.setFont("helvetica", "bold");
      doc.text(value, x + 10, y + 36);
      doc.setFont("helvetica", "normal");
    });
    y += 70;
  }

  for (const s of sections) {
    if (y > 720) {
      doc.addPage();
      y = 50;
    }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(...navy);
    doc.text(s.title, 40, y);
    if (s.subtitle) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(s.subtitle, 40, y + 12);
    }
    autoTable(doc, {
      startY: y + (s.subtitle ? 20 : 8),
      head: [s.head],
      body: s.body.map((r) => r.map(String)),
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 4, lineColor: [232, 225, 212] },
      headStyles: { fillColor: navy, textColor: 255 },
      alternateRowStyles: { fillColor: [253, 252, 250] },
      margin: { left: 40, right: 40 },
    });
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    y = (doc as any).lastAutoTable.finalY + 28;
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Demonstration data · Generated by DwellMender · Page ${i} of ${pages}`, 40, doc.internal.pageSize.getHeight() - 20);
  }
  doc.save(filename);
}
